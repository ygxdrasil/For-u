/** Which nodes in a workflow can change something in the outside world. */
export function writeNodesIn(workflow) {
  const out = [];
  for (const node of workflow?.nodes ?? []) {
    if (node.disabled) continue;
    const params = node.parameters ?? {};
    if (
      isWriteOperation({
        type: node.type,
        resource: typeof params.resource === 'string' ? params.resource : null,
        operation: typeof params.operation === 'string' ? params.operation : null,
      })
    ) {
      out.push(node.name);
    }
  }
  return out;
}

function summariseExecution(execution) {
  const resultData = execution?.data?.resultData ?? {};
  const runData = resultData.runData ?? {};
  const nodes = Object.entries(runData).map(([name, runs]) => {
    const run = runs?.[0] ?? {};
    const items = run.data?.main?.[0] ?? [];
    return {
      node: name,
      status: run.error ? 'error' : 'ok',
      error: run.error?.message ?? null,
      itemCount: Array.isArray(items) ? items.length : null,
      firstItem: Array.isArray(items) && items[0] ? JSON.stringify(items[0].json ?? items[0]).slice(0, 600) : null,
    };
  });
  return {
    id: execution?.id,
    workflowId: execution?.workflowId,
    status: execution?.status,
    startedAt: execution?.startedAt,
    stoppedAt: execution?.stoppedAt,
    lastNodeExecuted: resultData.lastNodeExecuted ?? null,
    nodes,
  };
}

/**
 * Dry run: prove the data path without letting anything reach a real system.
 *
 * The write nodes are disabled rather than removed, so the shape of the
 * workflow is unchanged and the report can say exactly what each one would
 * have received. The test copy is a separate workflow — the original is never
 * modified to run a test.
 */
async function dryRun({ n8n, store, onStatus, id, pinData }) {
  if (!n8n) return fail('No n8n connection is configured.');

  let original;
  try {
    original = await n8n.getWorkflow(id);
  } catch (e) {
    return fail(`Could not fetch workflow ${id}: ${e.message}`);
  }

  const writers = writeNodesIn(original);
  onStatus(writers.length ? `Disabling ${writers.length} write node(s) for the dry run…` : 'No write nodes to disable.');

  const testWorkflow = {
    name: `${original.name} [test]`,
    nodes: (original.nodes ?? []).map((n) => (writers.includes(n.name) ? { ...n, disabled: true } : { ...n })),
    connections: original.connections ?? {},
    settings: original.settings ?? {},
  };
  if (pinData && Object.keys(pinData).length) testWorkflow.pinData = pinData;

  let created;
  try {
    created = await n8n.createWorkflow(testWorkflow);
  } catch (e) {
    return fail(`Could not create the test copy: ${e.message}`);
  }

  const testId = created.workflow?.id;
  onStatus(`Running test copy ${testId}…`);

  const run = await n8n.runWorkflow(testId);

  let execution = null;
  let readError = null;
  if (run.ran) {
    try {
      execution = await n8n.latestExecution(testId);
    } catch (e) {
      readError = e.message;
    }
  }

  const assessment = run.ran
    ? assessExecution({ execution, readError, disabledWriteNodes: writers })
    : {
        verdict: 'unconfirmed',
        headline: 'Could not run it from the API',
        detail: run.error,
        evidence: { testWorkflowId: testId, tried: run.tried },
      };

  return ok({
    testWorkflowId: testId,
    testWorkflowName: testWorkflow.name,
    disabledWriteNodes: writers,
    ran: run.ran,
    assessment,
    execution: execution ? summariseExecution(execution) : null,
    wouldHaveSent: writers.length
      ? `These nodes were disabled and sent nothing: ${writers.join(', ')}. Their input is visible in the execution of the node feeding them.`
      : null,
    note: 'The test copy is left in place, inactive, so you can inspect it. Nothing was deleted.',
  });
}

/**
 * Probe workflow: the only honest way to get real picker values without the
 * user's tokens ever leaving n8n. Builds a minimal read-only workflow, runs it,
 * reads the output, then archives it.
 */
async function runProbe({ n8n, store, onStatus, nodeType, resource, operation, credentialType, credentialId, parameters }) {
  if (!n8n) return fail('No n8n connection is configured.');

  const catalogNode = getNode(nodeType);
  if (!catalogNode) return fail(`Unknown node type "${nodeType}".`);

  const op = operation ?? 'getAll';
  if (isWriteOperation({ type: nodeType, resource: resource ?? null, operation: op })) {
    return fail(`Refusing to probe with operation "${op}" — probes are read-only. Use a list/get operation.`);
  }

  const probe = {
    name: `[assistant probe] ${catalogNode.displayName} ${resource ?? ''} ${op}`.trim(),
    nodes: [
      { id: 'trigger', name: 'Start', type: 'n8n-nodes-base.manualTrigger', typeVersion: 1, position: [0, 0], parameters: {} },
      {
        id: 'probe',
        name: 'List',
        type: nodeType,
        typeVersion: catalogNode.version ?? 1,
        position: [220, 0],
        parameters: { ...(resource ? { resource } : {}), operation: op, returnAll: false, limit: 100, ...(parameters ?? {}) },
        credentials: { [credentialType]: { id: credentialId, name: credentialId } },
      },
    ],
    connections: { Start: { main: [[{ node: 'List', type: 'main', index: 0 }]] } },
    settings: {},
  };

  onStatus('Running a read-only probe against your credential…');

  let created;
  try {
    created = await n8n.createWorkflow(probe);
  } catch (e) {
    return fail(`Could not create the probe workflow: ${e.message}`);
  }
  const probeId = created.workflow?.id;

  const run = await n8n.runWorkflow(probeId);
  let execution = null;
  let readError = null;
  if (run.ran) {
    try {
      execution = await n8n.latestExecution(probeId);
    } catch (e) {
      readError = e.message;
    }
  }

  // Always retire the probe, whatever happened. Archive, never delete.
  let retired = null;
  try {
    retired = await n8n.archiveWorkflow(probeId);
  } catch (e) {
    retired = { archived: false, error: e.message };
  }

  if (!run.ran) {
    return fail(
      `The probe could not be run from the API (${run.error}). I have no real values, so I will not guess one — pick the value in n8n and tell me, or run the probe workflow manually.`,
      { probeWorkflowId: probeId, retired },
    );
  }

  const assessment = assessExecution({ execution, readError });
  if (assessment.verdict !== 'worked') {
    return fail(`The probe ran but I could not read real values back: ${assessment.detail}`, { probeWorkflowId: probeId, assessment, retired });
  }

  const runData = execution?.data?.resultData?.runData?.List?.[0]?.data?.main?.[0] ?? [];
  const values = runData.map((item) => item.json ?? item).slice(0, 100);

  return ok({
    values,
    count: values.length,
    probeWorkflowId: probeId,
    retired,
    note: 'These are real values read through your credential inside n8n. Use one of them verbatim; do not adapt or shorten an id.',
  });
}
